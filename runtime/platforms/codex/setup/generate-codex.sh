codex_prefix_text() {
  local file="$1"
  [ -n "$PREFIX" ] || return 0

  python3 - "$file" <<'PY'
from pathlib import Path
import re
import sys

path = Path(sys.argv[1])
text = path.read_text()

commands = [
    "design-review",
    "autoresearch",
    "architect",
    "research",
    "continue",
    "reflect",
    "analyze",
    "design",
    "review",
    "status",
    "build",
    "learn",
    "fix",
    "map",
    "qa",
]
cmd_pattern = "|".join(re.escape(cmd) for cmd in commands)

def replace_command(match: re.Match[str]) -> str:
    sigil, cmd = match.group(1), match.group(2)
    if sigil == "/" and cmd == "review":
        return match.group(0)
    return f"{sigil}sage:{cmd}"

text = re.sub(
    rf"(?<![\w])([$/])({cmd_pattern})(?![\w:-])",
    replace_command,
    text,
)
text = re.sub(
    rf"(\.agents/skills/)({cmd_pattern})(?=(/|\b))",
    lambda m: f"{m.group(1)}sage:{m.group(2)}",
    text,
)

path.write_text(text)
PY
}

set_skill_name_frontmatter() {
  local file="$1"
  local skill_name="$2"

  python3 - "$file" "$skill_name" <<'PY'
from pathlib import Path
import re
import sys

path = Path(sys.argv[1])
skill_name = sys.argv[2]
text = path.read_text()
text, count = re.subn(r"^name:.*$", f"name: {skill_name}", text, count=1, flags=re.MULTILINE)
if count != 1:
    raise SystemExit(f"Expected exactly one frontmatter name line in {path}")
path.write_text(text)
PY
}

# ── Tier detection ──
# Reads SKILL.md frontmatter. Returns "workflow" if `tier: workflow`,
# else "direct" (default for all other values + missing field).
skill_tier() {
  local file="$1"
  [ -f "$file" ] || { echo "direct"; return; }
  python3 - "$file" <<'PY'
import re, sys
text = open(sys.argv[1]).read()
m = re.match(r"^---\n(.*?)\n---", text, re.DOTALL)
if not m:
    print("direct"); raise SystemExit
fm = m.group(1)
tier = "direct"
for line in fm.splitlines():
    line = line.strip()
    if line.startswith("tier:"):
        v = line.split(":", 1)[1].strip().strip('"').strip("'")
        tier = v or "direct"
        break
print("workflow" if tier == "workflow" else "direct")
PY
}

# ── Behavioral isolation YAML emission (M3, ADR-4 v3) ──
# Emits .agents/skills/<name>/agents/openai.yaml with:
#   - policy.allow_implicit_invocation: false
#   - interface.short_description: bit-identical copy of SKILL.md description
# Idempotent: re-runs produce 0 diff. Direct skills only (workflow tier
# stays reactive). The `name:` field in SKILL.md is NEVER altered — slash
# command compatibility preserved per ADR-4.
emit_skill_isolation_yaml() {
  local skill_md="$1"
  local yaml_dir="$2"
  python3 - "$skill_md" "$yaml_dir" <<'PY'
import re, sys, os
skill_md = sys.argv[1]
yaml_dir = sys.argv[2]
text = open(skill_md).read()
m = re.match(r"^---\n(.*?)\n---", text, re.DOTALL)
if not m:
    raise SystemExit(0)  # no frontmatter → skip
fm = m.group(1)
# Extract description: supports inline and folded (>) block scalar.
desc_lines = []
in_desc = False
for raw in fm.splitlines():
    if raw.startswith("description:"):
        rest = raw.split(":", 1)[1].strip()
        if rest in (">", ">-", "|", "|-"):
            in_desc = True
            continue
        elif rest:
            desc_lines.append(rest)
            in_desc = False
            continue
        else:
            in_desc = True
            continue
    if in_desc:
        if raw and not raw.startswith(" ") and not raw.startswith("\t"):
            in_desc = False
            continue
        desc_lines.append(raw.strip())
desc = " ".join(s for s in desc_lines if s).strip()
if not desc:
    desc = ""
# YAML emission: simple double-quoted scalar with escaping.
def q(s):
    s = s.replace("\\", "\\\\").replace('"', '\\"').replace("\n", " ")
    return f'"{s}"'
out_dir = yaml_dir
os.makedirs(out_dir, exist_ok=True)
yaml_path = os.path.join(out_dir, "openai.yaml")
content = (
    "# Auto-generated by Sage. Do not edit by hand.\n"
    "# Behavioral isolation per ADR-4 v3: prevents Codex auto-suggest\n"
    "# on description match. Workflow skills do NOT receive this file.\n"
    "policy:\n"
    "  allow_implicit_invocation: false\n"
    "interface:\n"
    f"  short_description: {q(desc)}\n"
)
# Idempotent write: skip if identical
if os.path.exists(yaml_path):
    if open(yaml_path).read() == content:
        raise SystemExit(0)
with open(yaml_path, "w") as f:
    f.write(content)
PY
}

alternate_skill_name() {
  local skill_name="$1"

  if [ "$skill_name" = "sage" ]; then
    return 0
  fi

  case "$skill_name" in
    sage:*) printf '%s\n' "${skill_name#sage:}" ;;
    *) printf 'sage:%s\n' "$skill_name" ;;
  esac
}

remove_stale_skill_variant() {
  local skill_name="$1"
  local stale_name
  local stale_dir

  stale_name="$(alternate_skill_name "$skill_name")"
  [ -n "$stale_name" ] || return 0

  stale_dir="$AGENTS_DIR/skills/$stale_name"
  if [ "$stale_name" != "$skill_name" ] && [ -d "$stale_dir" ]; then
    rm -rf "$stale_dir"
  fi
}

